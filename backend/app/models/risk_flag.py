import uuid
import enum
from datetime import datetime, timezone
from sqlalchemy import Column, String, Float, Boolean, Text, DateTime, ForeignKey, Uuid
from sqlalchemy.orm import relationship

from app.core.database import Base


class FlagSeverity(str, enum.Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class VerificationFlag(Base):
    """
    Explainable Risk and Verification Flag generated by the Cross-Checker and Risk Engine.
    Provides verifiable, human-in-the-loop evidence with confidence scores and rule citations.
    """
    __tablename__ = "verification_flags"

    id = Column(Uuid(as_uuid=True), primary_key=True, default=uuid.uuid4, index=True)
    application_id = Column(
        Uuid(as_uuid=True),
        ForeignKey("applications.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    field_name = Column(String(100), nullable=False, index=True)  # e.g., "full_name", "annual_income", "institution_name"
    source_doc_a = Column(String(100), nullable=False)  # e.g., "caste_cert", "profile", "application"
    value_a = Column(String(500), nullable=True)
    source_doc_b = Column(String(100), nullable=False)  # e.g., "income_cert", "marksheet", "scheme_policy"
    value_b = Column(String(500), nullable=True)
    similarity_score = Column(Float, nullable=True)  # RapidFuzz similarity ratio (0.0 to 100.0)
    severity = Column(String(50), nullable=False, default=FlagSeverity.LOW.value, index=True)
    rule_triggered = Column(Text, nullable=False)  # Explainable rule narrative e.g. "Income exceeds policy limit..."
    recommended_action = Column(Text, nullable=False, default="Review source documents and resolve the discrepancy")
    is_resolved = Column(Boolean, nullable=False, default=False, index=True)
    resolution_notes = Column(Text, nullable=True)
    
    created_at = Column(DateTime(timezone=True), default=lambda: datetime.now(timezone.utc), nullable=False)
    updated_at = Column(
        DateTime(timezone=True),
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
        nullable=False,
    )

    # Relationships
    application = relationship("Application", back_populates="verification_flags")

    def __repr__(self) -> str:
        return f"<VerificationFlag id={self.id} field={self.field_name} sev={self.severity} score={self.similarity_score}>"
